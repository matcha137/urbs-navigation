/**
 * 落とさないが順位は下げる。誰でも入れるが「行きたい場所」ではないもの。
 *
 * 区役所や出張所はロビーとトイレがあり、雨宿りと休憩には実際に使える。
 * 他に選択肢があるときだけ後ろに回す。
 */
export const ODD_AS_DESTINATION = /(区役所|出張所|防災センター|会館$)/;

/** ODD_AS_DESTINATION に当たったときのスコア倍率。 */
export const ODD_PENALTY = 0.6;

/**
 * 同じカテゴリの場所を続けて選んだときの倍率。
 *
 * 訪問履歴が無いので novelty (新規性) は本来出せない。
 * せめて1つのプランの中で公園3つ・施設3つを並べないようにする。
 */
export const REPEAT_CATEGORY_PENALTY = 0.5;

/**
 * 「水辺」と見なす名前。**宣言された属性ではなく名前からの判定**。
 *
 * category='riverside' は11件しか無く、実体は乗船場とスロープで「歩く場所」
 * ではない。木場駅・東陽町駅には半径1.2km に1件も無く、モードとして成立しない。
 *
 * 江東区は堀と運河を埋めて公園にした土地なので、名前に水の語が残っている。
 * この語彙で拾うと 83件 になり、各駅 3〜19件で選択肢として成立する。
 *
 * 推定である以上、当たった場所には必ず「名前から拾った」と分かる注記を付けること。
 */
export const WATERSIDE_KEYWORDS = [
  '水辺', '親水', '運河', '堀', 'River',
  '臨海', '浜', '汐', '潮', '洲', '波',
] as const;

/**
 * 「川」だけは地名を拾ってしまうので別扱いにする。
 *
 * 江東区の「深川」は地名であって水辺ではない。素朴に '川' で当てると
 * 深川公園・深川江戸資料館・深川スポーツセンターなど7件が水辺として出てきて、
 * 「水辺を歩く」で屋内の資料館が先頭に来る。
 *
 * そこで **深川を取り除いてもなお '川' が残る名前** だけを水辺とする。
 * 「小名木川」「竪川河川敷公園」「洲崎川緑道公園」は残り、「深川公園」は落ちる。
 */
export const WATERSIDE_RIVER = { token: '川', ignoreWord: '深川' } as const;
