/**
 * 「行き先として提示していいか」の判定表。
 *
 * 公共施設一覧には、誰でも入れる施設 (文化センター・スポーツセンター・図書館) と、
 * **利用者が限定されている施設** (障害者作業所・老人福祉センター・グループホーム) と、
 * **予約しないと入れない施設** (地区集会所・区民館) が混在している。
 *
 * バリアフリー情報を売りにするアプリが「あすなろ作業所へ行きましょう」と
 * 提案するのは端的に間違いなので、行き先の母集団から外す。
 *
 * D1 からは消さない。トイレや雨宿りの実在情報としては正しく、
 * 出典カウント (T-92) の根拠でもあるため。行き先クエリでだけ除く。
 *
 * ---
 * 本来はここではなく ETL の除外ルール (etl/mappings/koto-facilities.mjs) に
 * 置くべき性質のもの。そちらに移すと再 normalize + 再 seed が要るので、
 * まずは API 側で外している。移すときは EXCLUDE_KEYWORDS に合流させること。
 */

